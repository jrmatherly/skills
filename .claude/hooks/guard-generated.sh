#!/bin/bash
# PreToolUse hook for Edit and Write: refuse a hand edit to a tree a sync
# script regenerates, since the next sync would discard it. The scripts
# themselves write through Bash, which this hook does not see.
set -euo pipefail

# Without jq the path can't be read: allow, the rule in .claude/rules still applies
command -v jq > /dev/null || exit 0
file=$(jq -r '.tool_input.file_path // empty')
root=${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd -P)}

case ${file#"$root"/} in
  plugins/jstack/*)
    why="plugins/jstack/ is generated by scripts/sync-jstack. Change jstack/substitutions.tsv or a patch in jstack/patches/ instead (README, \"Change or refresh a patch\")." ;;
  skills/supabase-prompts/references/* | skills/supabase-prompts/LICENSE)
    why="These files are Supabase's, fetched by scripts/sync-supabase-prompts. Move the pin in that script instead; hand-written notes go in skills/supabase-prompts/SKILL.md." ;;
  *) exit 0 ;;
esac

jq -n --arg why "$why" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: "deny", permissionDecisionReason: $why}}'
